## 4 堆疊與佇列
本章介紹兩種最基本的線性結構，以及它們各自適合的情境。

### 4.1 堆疊（Stack）
> 🎯 本節目標：理解堆疊「後進先出」的特性。

**堆疊**是一種只能從同一端存取的線性結構。
- 放入資料稱為 **push**，取出稱為 **pop**。
- 最後放進去的資料，會最先被拿出來，稱為 **LIFO**（Last In, First Out）。

**例：**瀏覽器的「上一頁」就是堆疊：最後看的網頁最先被退回。

> ✅ 重點：堆疊只操作頂端，後進先出。

### 4.2 佇列（Queue）
> 🎯 本節目標：理解佇列「先進先出」的特性，並和堆疊比較。

**佇列**從尾端加入、從前端取出，就像排隊。

| 結構 | 存取規則 | 常見用途 |
|---|---|---|
| 堆疊 | 後進先出 LIFO | 函式呼叫、復原（Undo） |
| 佇列 | 先進先出 FIFO | 印表機排程、BFS |

**例：**印表機依照送出的順序列印文件。

> ✅ 重點：佇列先進先出，和堆疊的取出順序相反。

### 4.3 本章小測驗
1. 堆疊和佇列的取出順序有什麼不同？
   - 答：堆疊後進先出（LIFO），佇列先進先出（FIFO）。
2. 「復原（Undo）」功能適合用哪一種結構？
   - 答：堆疊，因為要先復原最後一次的操作。
3. 廣度優先搜尋（BFS）通常用哪一種結構？
   - 答：佇列。

## 5 樹
本章介紹階層式資料最常用的結構：樹。

### 5.1 二元樹
> 🎯 本節目標：認識二元樹的基本名詞。

**二元樹**的每個節點最多有兩個子節點：**左子樹**與**右子樹**。
- 最上面的節點稱為 **根（root）**。
- 沒有子節點的節點稱為 **葉（leaf）**。

**例：**比賽的淘汰賽對戰表就是一棵二元樹。

> ✅ 重點：二元樹每個節點最多兩個孩子。
